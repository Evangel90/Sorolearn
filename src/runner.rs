//! Turns exercise files into Cargo packages and runs their tests.
//!
//! Every exercise is a single `.rs` file. To compile it as a Soroban contract
//! we generate a hidden workspace under `.sorolearn/` with one tiny package
//! per exercise whose `[lib] path` points back at the learner's file. All
//! packages share one target dir, so the SDK is only compiled once.

use crate::info::{Exercise, Info, SOROBAN_SDK_VERSION};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

pub const TARGET_DIR: &str = ".sorolearn/target";

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Source {
    Exercises,
    Solutions,
}

impl Source {
    fn workspace_dir(self) -> PathBuf {
        match self {
            Source::Exercises => PathBuf::from(".sorolearn/exercises"),
            Source::Solutions => PathBuf::from(".sorolearn/solutions"),
        }
    }

    fn file(self, ex: &Exercise) -> PathBuf {
        match self {
            Source::Exercises => ex.path(),
            Source::Solutions => ex.solution_path(),
        }
    }
}

pub struct Outcome {
    pub success: bool,
    pub output: String,
}

/// (Re)generate the hidden Cargo workspace for the given source tree.
pub fn ensure_workspace(info: &Info, source: Source) -> std::io::Result<()> {
    let root = source.workspace_dir();
    let crates = root.join("crates");
    fs::create_dir_all(&crates)?;

    let workspace = format!(
        r#"# Generated by sorolearn. Do not edit; edit the files in exercises/ instead.
[workspace]
resolver = "2"
members = ["crates/*"]

[workspace.dependencies]
soroban-sdk = "={SOROBAN_SDK_VERSION}"

[profile.dev]
debug = 0
"#
    );
    write_if_changed(&root.join("Cargo.toml"), &workspace)?;


    // Absolute paths make compiler errors point straight at the learner's file.
    // The workspace is regenerated on every run, so moving the repo is fine.
    let repo_root = std::env::current_dir()?;
    for ex in &info.exercises {
        let dir = crates.join(&ex.name);
        fs::create_dir_all(&dir)?;
        let lib_path = repo_root.join(source.file(ex));
        let manifest = format!(
            r#"[package]
name = "{name}"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
path = '{lib}'
doctest = false

[dependencies]
soroban-sdk = {{ workspace = true }}

[dev-dependencies]
soroban-sdk = {{ workspace = true, features = ["testutils"] }}
"#,
            name = ex.name,
            lib = lib_path.display()
        );
        write_if_changed(&dir.join("Cargo.toml"), &manifest)?;
    }
    Ok(())
}

fn write_if_changed(path: &Path, contents: &str) -> std::io::Result<()> {
    if fs::read_to_string(path).ok().as_deref() != Some(contents) {
        fs::write(path, contents)?;
    }
    Ok(())
}

/// Compile the exercise and run its tests.
pub fn run(ex: &Exercise, source: Source) -> Outcome {
    cargo_test(ex, source)
}

fn cargo_test(ex: &Exercise, source: Source) -> Outcome {
    let manifest = source.workspace_dir().join("Cargo.toml");
    let result = cargo()
        .args(["test", "--quiet", "--color", "always", "--manifest-path"])
        .arg(&manifest)
        .args(["-p", &ex.name])
        .stdin(Stdio::null())
        .output();

    match result {
        Ok(out) => {
            let mut output = String::from_utf8_lossy(&out.stderr).into_owned();
            output.push_str(&String::from_utf8_lossy(&out.stdout));
            Outcome { success: out.status.success(), output }
        }
        Err(e) => Outcome {
            success: false,
            output: format!("Failed to run cargo: {e}. Is Rust installed? See https://rustup.rs"),
        },
    }
}

fn cargo() -> Command {
    let mut cmd = Command::new("cargo");
    cmd.env("CARGO_TARGET_DIR", TARGET_DIR);
    cmd
}

/// Snapshot the pristine exercises so `sorolearn reset` can restore them.
pub fn ensure_originals(info: &Info) -> std::io::Result<()> {
    for ex in &info.exercises {
        let backup = original_path(ex);
        if !backup.exists() {
            fs::create_dir_all(backup.parent().unwrap())?;
            fs::copy(ex.path(), &backup)?;
        }
    }
    Ok(())
}

pub fn original_path(ex: &Exercise) -> PathBuf {
    Path::new(".sorolearn/originals").join(ex.path())
}
